def theme_of_unit(unit: str) -> str:
    """把来源单元标题变成可用的主题名：去掉 `专题NN ` / `第NN讲 ` 之类编号。

    为什么用专题名当主题：专题本身就是教辅给出的连贯主题划分，而且已经过人工核对
    （见 FIXES）；而老树里的节名来自 boundary 前缀，已证实不可信
    （`牛顿第二定律` 曾挂在"3 牛顿第三定律"下）。
    """
    title = re.sub(r"^(专题|微专题)\s*\d+\s*", "", unit or "")
    title = re.sub(r"^第\s*\d+\s*讲\s*", "", title)
    title = re.sub(r"^[0-9]+(\.[0-9]+)?\s*", "", title)
    title = re.sub(r"[（(][^）)]*(学生版|教师版|全国通用)[^）)]*[）)]", "", title)
    return title.strip()[:60]


def build_rows() -> list[dict[str, str]]:
    pack = pack_io.load_json(pack_io.pack_path())
    units: dict[str, Counter] = defaultdict(Counter)
    samples: dict[str, list[str]] = defaultdict(list)
    for _s, _t, point in pack_io.iter_points(pack):
        unit = source_unit(point.get("sourceLocator", ""))
        match = _LOCATOR.match(point.get("boundary") or "")
        units[unit][match.group(1) if match else "(无定位)"] += 1
        if len(samples[unit]) < 4:
            samples[unit].append(point["name"][:24])

    rows: list[dict[str, str]] = []
    for unit, places in sorted(units.items()):
        current = places.most_common(1)[0][0]
        fix = None
        for prefix, value in FIXES.items():
            if unit.startswith(prefix):
                fix = value
                break
        if fix:
            book, chapter, decision = fix
        else:
            book, chapter, decision = "", "", "todo"
        rows.append({
            "source_unit": unit,
            "nodes": str(sum(places.values())),
            "current_place": current,
            "book": book,
            "chapter": chapter,
            "decision": decision,
            "samples": " / ".join(samples[unit]),
        })
    return rows


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args(argv)

    rows = build_rows()
    counts = Counter(r["decision"] for r in rows)
    print(f"来源单元 {len(rows)} 个：{dict(counts)}")
    todo = [r for r in rows if r["decision"] == "todo"]
    if todo:
        print()
        print("尚未核对（必须清零才能定稿）：")
        for row in todo:
            print(f"   {row['nodes']:>4}  {row['source_unit'][:46]}  [{row['current_place'][:24]}]")
    fixed = [r for r in rows if r["decision"] == "fix"]
    print()
    print(f"修正 {len(fixed)} 个单元，按科：{dict(Counter(r['book'][:2] for r in fixed))}")

    if args.write:
        path = tables.TABLES_DIR / "chapter_by_source.csv"
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w", encoding="utf-8", newline="") as fh:
            writer = csv.DictWriter(fh, fieldnames=[
                "source_unit", "nodes", "current_place", "book", "chapter",
                "decision", "samples",
            ])
            writer.writeheader()
            writer.writerows(rows)
        print(f"已写入 {path}")
    return 1 if todo else 0


if __name__ == "__main__":
    raise SystemExit(main())
